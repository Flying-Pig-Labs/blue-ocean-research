#!/usr/bin/env python3
"""
Jobs-to-be-Done Researcher using EXA API.

This module serves as the second stage in the 7-stage product innovation pipeline.
It takes the analysis results from research_analyzer.py and uses the EXA search API
to find real-world customer context, extracting authentic Jobs-to-be-Done (JTBD)
from various online sources.

Key Features:
- Intelligent query construction from analysis results
- Multi-source searching (Reddit, reviews, interviews, news, tutorials)
- Pattern-based JTBD extraction from search results
- Optional Claude AI synthesis for comprehensive reporting
- Rich terminal UI with progress tracking

Search Sources:
1. Reddit - Authentic user frustrations and discussions
2. Product Reviews - Comparison and pain point insights
3. Interviews/Case Studies - Deep user workflow understanding
4. Industry News - Market trends and challenges
5. Tutorials/Blogs - Solution attempts and workarounds

Usage:
    # Basic usage with default analysis file
    python jobs_researcher.py

    # Specify custom input file
    python jobs_researcher.py --input custom_analysis.md

    # Test mode
    python jobs_researcher.py --test

Environment Variables Required:
    - EXA_API_KEY: EXA search API key
    - ANTHROPIC_API_KEY: Claude AI API key (optional, for synthesis)

Output:
    Creates 'pain_points.txt' containing extracted JTBD patterns.
"""

import os
import sys
import json
import argparse
from typing import Dict, List, Optional
from datetime import datetime
from dotenv import load_dotenv
from exa_py import Exa
from rich.console import Console
from rich.panel import Panel
from rich.progress import Progress, SpinnerColumn, TextColumn
from rich.table import Table
from rich.markdown import Markdown
import anthropic

# Load environment variables
load_dotenv()

# Initialize Rich console
console = Console()


class JobsResearcher:
    """
    Research Jobs-to-be-Done using EXA search API.

    This class orchestrates the JTBD research process by analyzing previous
    pipeline results, constructing intelligent search queries, executing
    multi-source searches via EXA API, and extracting authentic customer
    jobs from the results.

    Attributes:
        exa: EXA API client for web searching
        anthropic_client: Optional Claude AI client for synthesis
        model: Claude model identifier for synthesis

    Example:
        researcher = JobsResearcher()
        researcher.run("analysis_results.md")
    """

    def __init__(self):
        """
        Initialize EXA and Anthropic clients.

        Sets up the EXA search client (required) and optionally initializes
        the Anthropic client for AI-powered synthesis. Handles missing API
        keys gracefully, with EXA being mandatory and Anthropic optional.

        Raises:
            SystemExit: If EXA_API_KEY is not found in environment
        """
        # EXA setup
        self.exa_api_key = os.getenv("EXA_API_KEY")
        if not self.exa_api_key:
            console.print(
                "[red]Error: EXA_API_KEY not found in environment variables![/red]"
            )
            sys.exit(1)

        try:
            self.exa = Exa(self.exa_api_key)
        except Exception as e:
            console.print(f"[red]Error initializing EXA client: {e}[/red]")
            sys.exit(1)

        # Anthropic setup (for summarization)
        self.anthropic_api_key = os.getenv("ANTHROPIC_API_KEY")
        if self.anthropic_api_key:
            try:
                self.anthropic_client = anthropic.Anthropic(
                    api_key=self.anthropic_api_key
                )
                self.model = "claude-3-5-sonnet-20241022"
            except Exception as e:
                console.print(
                    f"[yellow]Warning: Anthropic client initialization failed: {e}[/yellow]"
                )
                self.anthropic_client = None
        else:
            self.anthropic_client = None

    def load_analysis_results(self, filepath: str) -> str:
        """
        Load the analysis results from previous pipeline step.

        Reads the markdown file generated by research_analyzer.py containing
        industry verticals, user personas, pain points, and solution types.

        Args:
            filepath: Path to the analysis results file (typically analysis_results.md)

        Returns:
            str: Raw content of the analysis file

        Raises:
            SystemExit: If the file is not found
        """
        try:
            with open(filepath, "r") as f:
                content = f.read()
            console.print(f"[green]✅ Loaded analysis results from {filepath}[/green]")
            return content
        except FileNotFoundError:
            console.print(f"[red]Error: Analysis file not found: {filepath}[/red]")
            sys.exit(1)

    def extract_key_elements(self, analysis: str) -> Dict[str, List[str]]:
        """
        Extract key elements from the analysis for search queries.

        Parses the structured analysis document to extract lists of verticals,
        personas, pain points, and solution types. These elements are used to
        construct targeted search queries.

        Args:
            analysis: Raw analysis content from the previous pipeline stage

        Returns:
            Dict[str, List[str]]: Dictionary containing lists of:
                - verticals: Industry sectors identified
                - personas: User types and roles
                - pain_points: Key problems and frustrations
                - solution_types: Potential solution approaches
        """
        elements = {
            "verticals": [],
            "personas": [],
            "pain_points": [],
            "solution_types": [],
        }

        # Simple extraction based on section headers
        sections = {
            "Industry Verticals": "verticals",
            "User Personas": "personas",
            "Pain Points": "pain_points",
            "Solution Types": "solution_types",
        }

        current_section = None
        lines = analysis.split("\n")

        for line in lines:
            # Check for section headers
            for header, key in sections.items():
                if header in line and line.startswith("#"):
                    current_section = key
                    break

            # Extract bullet points or key phrases
            if current_section and (
                line.strip().startswith("-") or line.strip().startswith("•")
            ):
                item = line.strip().lstrip("-•").strip()
                if len(item) > 5:  # Filter out very short items
                    elements[current_section].append(item[:100])  # Limit length

        return elements

    def construct_search_queries(
        self, elements: Dict[str, List[str]]
    ) -> List[Dict[str, str]]:
        """
        Construct targeted search queries for different source types.

        Creates intelligent search queries by combining extracted elements
        in ways that are likely to surface authentic JTBD insights from
        different types of online sources.

        Query Types:
        - Reddit: User frustrations and daily workflow discussions
        - Reviews: Product comparisons highlighting gaps
        - Interviews: Deep user stories and case studies
        - News: Industry challenges and market trends
        - Tutorials: Workarounds indicating unmet needs

        Args:
            elements: Dictionary of extracted analysis elements

        Returns:
            List[Dict[str, str]]: List of query objects containing:
                - query: The search query string
                - type: Source type (reddit, reviews, etc.)
                - focus: What aspect we're looking for
        """
        queries = []

        # Get first few items from each category
        verticals = elements["verticals"][:3]
        personas = elements["personas"][:3]
        pain_points = elements["pain_points"][:3]

        # Reddit queries for authentic user discussions
        if verticals and personas:
            queries.append(
                {
                    "query": f"site:reddit.com ({' OR '.join(verticals[:2])}) frustration problem daily workflow",
                    "type": "reddit",
                    "focus": "user_frustrations",
                }
            )

        if personas and pain_points:
            queries.append(
                {
                    "query": f'site:reddit.com "{personas[0]}" "{pain_points[0]}" advice help',
                    "type": "reddit",
                    "focus": "pain_point_discussions",
                }
            )

        # Product review queries
        if verticals:
            queries.append(
                {
                    "query": f"product review comparison {verticals[0]} software tools pros cons",
                    "type": "reviews",
                    "focus": "product_comparisons",
                }
            )

        # Interview and case study queries
        if personas:
            queries.append(
                {
                    "query": f'interview case study "{personas[0]}" challenges workflow process',
                    "type": "interviews",
                    "focus": "user_interviews",
                }
            )

        # News and industry analysis
        if verticals and pain_points:
            queries.append(
                {
                    "query": f"{verticals[0]} industry challenges {pain_points[0]} trends 2024",
                    "type": "news",
                    "focus": "industry_analysis",
                }
            )

        # Blog posts and tutorials showing workarounds
        if pain_points:
            queries.append(
                {
                    "query": f"how to solve {pain_points[0]} tutorial guide workaround",
                    "type": "tutorials",
                    "focus": "solution_attempts",
                }
            )

        return queries

    def search_with_exa(self, queries: List[Dict[str, str]]) -> Dict[str, List[Dict]]:
        """
        Execute searches using EXA API.

        Performs web searches across multiple source types using the EXA API,
        with progress tracking and error handling. Retrieves full text content,
        highlights, and summaries when available.

        Args:
            queries: List of query objects to execute

        Returns:
            Dict[str, List[Dict]]: Search results organized by source type:
                - reddit: User discussion threads
                - reviews: Product review articles
                - interviews: Case studies and interviews
                - news: Industry news and analysis
                - tutorials: How-to guides and workarounds
        """
        results = {
            "reddit": [],
            "reviews": [],
            "interviews": [],
            "news": [],
            "tutorials": [],
        }

        console.print(
            "\n[bold cyan]Executing EXA searches for customer context...[/bold cyan]"
        )

        with Progress(
            SpinnerColumn(),
            TextColumn("[progress.description]{task.description}"),
            transient=False,
        ) as progress:
            task = progress.add_task("[cyan]Searching...", total=len(queries))

            for query_info in queries:
                query = query_info["query"]
                query_type = query_info["type"]

                progress.update(task, description=f"Searching {query_type}...")

                try:
                    # Execute search with EXA
                    search_results = self.exa.search_and_contents(
                        query, num_results=5, text=True, highlights=True, summary=True
                    )

                    # Process results
                    for result in search_results.results:
                        processed_result = {
                            "url": result.url,
                            "title": result.title,
                            "snippet": result.text[:500]
                            if hasattr(result, "text")
                            else "",
                            "highlights": result.highlights
                            if hasattr(result, "highlights")
                            else [],
                            "focus": query_info["focus"],
                            "published_date": result.published_date
                            if hasattr(result, "published_date")
                            else None,
                        }
                        results[query_type].append(processed_result)

                    progress.update(task, advance=1)

                except Exception as e:
                    console.print(
                        f"[yellow]Warning: Search failed for {query_type}: {e}[/yellow]"
                    )
                    progress.update(task, advance=1)

        # Summary of results
        total_results = sum(len(v) for v in results.values())
        console.print(
            f"\n[green]✅ Found {total_results} total results across {len(results)} categories[/green]"
        )

        return results

    def extract_jobs_to_be_done(
        self, search_results: Dict[str, List[Dict]], analysis_context: str
    ) -> List[Dict[str, str]]:
        """
        Extract Jobs-to-be-Done from search results.

        Analyzes search results to identify authentic JTBD patterns using
        linguistic markers like "I need to", "trying to", "struggling with".
        Extracts context around these patterns to understand the full job.

        Pattern Recognition:
        - Need statements: "I need to", "I want to"
        - Problem indicators: "struggling with", "can't figure out"
        - Desire expressions: "wish I could", "if only"
        - Solution seeking: "how to", "looking for", "help me"

        Args:
            search_results: Categorized search results from EXA
            analysis_context: Original analysis for additional context

        Returns:
            List[Dict[str, str]]: Extracted jobs with:
                - source: Where the job was found
                - url: Source URL
                - title: Source title
                - job_context: The JTBD context snippet
                - focus: What aspect this relates to
                - pattern: Which linguistic pattern was matched
        """
        jobs = []

        # Process each category of results
        for category, results in search_results.items():
            for result in results:
                # Extract potential JTBD from each result
                if result.get("snippet"):
                    # Look for patterns indicating jobs/tasks
                    snippet = result["snippet"].lower()

                    # Common JTBD patterns
                    patterns = [
                        "i need to",
                        "i want to",
                        "trying to",
                        "help me",
                        "how to",
                        "looking for",
                        "struggling with",
                        "can't figure out",
                        "wish i could",
                        "if only",
                    ]

                    for pattern in patterns:
                        if pattern in snippet:
                            # Extract the context around the pattern
                            start = snippet.find(pattern)
                            end = min(start + 200, len(snippet))
                            context = snippet[start:end]

                            job = {
                                "source": category,
                                "url": result["url"],
                                "title": result["title"],
                                "job_context": context,
                                "focus": result.get("focus", ""),
                                "pattern": pattern,
                            }
                            jobs.append(job)
                            break

        return jobs

    def generate_jtbd_report(
        self,
        jobs: List[Dict[str, str]],
        search_results: Dict[str, List[Dict]],
        elements: Dict[str, List[str]],
    ) -> str:
        """
        Generate a comprehensive Jobs-to-be-Done report.

        Creates a structured markdown report summarizing all findings, including
        executive summary, key findings by source type, JTBD analysis table,
        and detailed job descriptions. Uses Claude AI for synthesis if available.

        Report Sections:
        - Executive Summary: Overview of findings
        - Key Findings by Source: Categorized insights
        - JTBD Analysis: Structured table or AI synthesis
        - Detailed Findings: Full job contexts
        - Pain Points Summary: Extracted for next pipeline stage

        Args:
            jobs: List of extracted JTBD patterns
            search_results: Full search results by category
            elements: Original analysis elements for context

        Returns:
            str: Complete markdown-formatted JTBD report
        """
        report = "# Jobs-to-be-Done Research Report\n\n"
        report += f"Generated on: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n"

        # Executive Summary
        report += "## Executive Summary\n\n"
        report += f"This report synthesizes real-world customer context from {sum(len(v) for v in search_results.values())} "
        report += f"sources including Reddit discussions, product reviews, interviews, and industry news. "
        report += f"We identified {len(jobs)} potential jobs-to-be-done across the analyzed verticals and personas.\n\n"

        # Key Findings by Source Type
        report += "## Key Findings by Source\n\n"

        for category, results in search_results.items():
            if results:
                report += f"### {category.title()}\n\n"
                report += f"*{len(results)} sources analyzed*\n\n"

                # Summarize top findings
                for i, result in enumerate(results[:3]):
                    report += f"**{i + 1}. [{result['title']}]({result['url']})**\n"
                    if result.get("highlights"):
                        report += f"   - Key insights: {', '.join(result['highlights'][:2])}\n"
                    report += f"   - Focus: {result.get('focus', 'general').replace('_', ' ').title()}\n\n"

        # Jobs-to-be-Done Table
        report += "## Jobs-to-be-Done Analysis\n\n"

        if self.anthropic_client and jobs:
            # Use Claude to synthesize and structure the jobs
            report += self._synthesize_jtbd_with_claude(jobs, elements)
        else:
            # Fallback to structured extraction
            report += self._structure_jtbd_table(jobs, elements)

        # Detailed Findings
        report += "\n## Detailed Customer Context\n\n"

        # Group jobs by focus area
        jobs_by_focus = {}
        for job in jobs:
            focus = job.get("focus", "other")
            if focus not in jobs_by_focus:
                jobs_by_focus[focus] = []
            jobs_by_focus[focus].append(job)

        for focus, focus_jobs in jobs_by_focus.items():
            report += f"### {focus.replace('_', ' ').title()}\n\n"
            for job in focus_jobs[:5]:  # Top 5 per category
                report += f'- **Pattern**: "{job["pattern"]}"\n'
                report += f"  - Context: {job['job_context']}\n"
                report += f"  - Source: [{job['source']}]({job['url']})\n\n"

        # Recommendations
        report += "## Recommendations\n\n"
        report += "Based on the Jobs-to-be-Done analysis:\n\n"
        report += "1. **High-Priority Jobs**: Focus on the most frequently mentioned frustrations\n"
        report += "2. **Quick Wins**: Address simple workflow improvements that appear across multiple sources\n"
        report += "3. **Strategic Opportunities**: Consider the deeper systemic issues revealed in interviews and case studies\n"
        report += "4. **Validation Next Steps**: Conduct targeted user interviews to validate these findings\n\n"

        return report

    def _synthesize_jtbd_with_claude(
        self, jobs: List[Dict[str, str]], elements: Dict[str, List[str]]
    ) -> str:
        """
        Use Claude to synthesize jobs into a structured table.

        Leverages Claude AI to analyze raw job contexts and create a well-structured
        JTBD table with job statements, frequency, current solutions, pain levels,
        and opportunity scores. Falls back to manual structuring on error.

        Args:
            jobs: List of extracted job patterns with contexts
            elements: Original analysis elements for additional context

        Returns:
            str: Markdown-formatted JTBD table with analysis
        """
        # Prepare context for Claude
        context = "Based on the following real-world customer insights, create a Jobs-to-be-Done table:\n\n"

        # Add analysis context
        context += "Target Verticals: " + ", ".join(elements["verticals"][:3]) + "\n"
        context += "Key Personas: " + ", ".join(elements["personas"][:3]) + "\n"
        context += (
            "Main Pain Points: " + ", ".join(elements["pain_points"][:3]) + "\n\n"
        )

        # Add job contexts
        context += "Customer Voices:\n"
        for job in jobs[:20]:  # Limit to prevent token overflow
            context += f"- {job['job_context']}\n"

        prompt = """Create a Jobs-to-be-Done table with these columns:
        1. Job Statement (When I... I want to... So I can...)
        2. Frequency (Daily/Weekly/Monthly)
        3. Current Solutions
        4. Pain Level (High/Medium/Low)
        5. Opportunity Score (1-10)
        
        Format as a markdown table. Focus on the most impactful and frequently mentioned jobs."""

        try:
            message = self.anthropic_client.messages.create(
                model=self.model,
                max_tokens=2000,
                temperature=0.7,
                system="You are an expert at Jobs-to-be-Done framework analysis.",
                messages=[{"role": "user", "content": context + "\n\n" + prompt}],
            )

            return message.content[0].text + "\n"

        except Exception as e:
            console.print(f"[yellow]Warning: Claude synthesis failed: {e}[/yellow]")
            return self._structure_jtbd_table(jobs, elements)

    def _structure_jtbd_table(
        self, jobs: List[Dict[str, str]], elements: Dict[str, List[str]]
    ) -> str:
        """
        Fallback method to structure JTBD table without Claude.

        Creates a basic JTBD table by processing job patterns, determining
        frequency from context clues, and organizing by source type.
        Used when Claude AI is unavailable or encounters errors.

        Args:
            jobs: List of extracted job patterns
            elements: Analysis elements (unused in basic version)

        Returns:
            str: Simple markdown table of jobs
        """
        table = "| Job Statement | Source Type | Frequency | Pain Indicator |\n"
        table += "|--------------|-------------|-----------|----------------|\n"

        # Process unique job patterns
        seen_patterns = set()

        for job in jobs[:15]:  # Top 15 jobs
            pattern_key = f"{job['pattern']}_{job['focus']}"
            if pattern_key not in seen_patterns:
                seen_patterns.add(pattern_key)

                # Extract job statement
                context = job["job_context"]
                if len(context) > 100:
                    context = context[:97] + "..."

                # Determine frequency based on keywords
                frequency = "Occasional"
                if any(
                    word in context.lower() for word in ["daily", "every day", "always"]
                ):
                    frequency = "Daily"
                elif any(word in context.lower() for word in ["weekly", "often"]):
                    frequency = "Weekly"

                # Add to table
                table += f"| {context} | {job['source'].title()} | {frequency} | {job['pattern']} |\n"

        return table + "\n"

    def extract_pain_points(
        self, jobs: List[Dict[str, str]], search_results: Dict[str, List[Dict]]
    ) -> List[str]:
        """
        Extract pain points for clustering analysis.

        Processes job contexts and search snippets to extract statements
        indicating user pain points, frustrations, and unmet needs.
        These are prepared for the next pipeline stage (clustering).

        Pain Point Indicators:
        - Negative emotions: frustrated, hate, annoying
        - Inability: can't, unable, difficult
        - Problems: issue, problem, struggle
        - Desires: wish, if only

        Args:
            jobs: Extracted JTBD patterns
            search_results: Full search results for deeper mining

        Returns:
            List[str]: Unique pain point statements for clustering
        """
        pain_points = []

        # Extract from job contexts
        for job in jobs:
            context = job.get("job_context", "")
            # Clean up and add if meaningful
            if len(context) > 20:
                pain_points.append(context.strip())

        # Extract from search result snippets
        for category, results in search_results.items():
            for result in results:
                snippet = result.get("snippet", "")
                # Look for pain point indicators in snippets
                indicators = [
                    "frustrated",
                    "difficult",
                    "can't",
                    "unable",
                    "problem",
                    "issue",
                    "struggle",
                    "hate",
                    "annoying",
                    "wish",
                ]

                for indicator in indicators:
                    if indicator in snippet.lower():
                        # Extract sentence containing the indicator
                        sentences = snippet.split(".")
                        for sentence in sentences:
                            if indicator in sentence.lower() and len(sentence) > 20:
                                pain_points.append(sentence.strip())
                                break
                        break

        # Deduplicate while preserving order
        seen = set()
        unique_pain_points = []
        for point in pain_points:
            if point not in seen:
                seen.add(point)
                unique_pain_points.append(point)

        return unique_pain_points

    def save_pain_points(
        self, pain_points: List[str], output_file: str = "pain_points.txt"
    ):
        """
        Save pain points to text file for clustering.

        Writes extracted pain points to a text file, one per line,
        for consumption by the cluster_jtbd.py module.

        Args:
            pain_points: List of pain point statements
            output_file: Output filename (default: "pain_points.txt")
        """
        with open(output_file, "w") as f:
            for point in pain_points:
                f.write(f"{point}\n")
        console.print(
            f"[green]✅ Extracted {len(pain_points)} pain points to {output_file}[/green]"
        )

    def run(
        self,
        analysis_file: str = "analysis_results.md",
        output_file: str = "jtbd_research.md",
    ):
        """
        Main execution flow for JTBD research.

        Orchestrates the complete JTBD research pipeline:
        1. Load analysis results from previous stage
        2. Extract key elements for search queries
        3. Construct and execute targeted searches
        4. Extract JTBD patterns from results
        5. Generate comprehensive report
        6. Extract and save pain points for clustering

        Args:
            analysis_file: Input file from research_analyzer.py
            output_file: Output filename for JTBD report

        Returns:
            Dict: Summary statistics of the research process
        """
        console.print(
            Panel.fit(
                "[bold green]Jobs-to-be-Done Research with EXA[/bold green]\n"
                "Searching for real-world customer context",
                border_style="green",
            )
        )

        # Step 1: Load analysis results
        analysis_content = self.load_analysis_results(analysis_file)

        # Step 2: Extract key elements
        elements = self.extract_key_elements(analysis_content)
        console.print("\n[cyan]Extracted elements for search:[/cyan]")

        table = Table(title="Search Elements")
        table.add_column("Category", style="cyan")
        table.add_column("Count", style="magenta")
        table.add_column("Examples", style="white")

        for category, items in elements.items():
            examples = ", ".join(items[:2]) + ("..." if len(items) > 2 else "")
            table.add_row(category.replace("_", " ").title(), str(len(items)), examples)

        console.print(table)

        # Step 3: Construct search queries
        queries = self.construct_search_queries(elements)
        console.print(f"\n[green]✅ Constructed {len(queries)} search queries[/green]")

        # Step 4: Execute searches
        search_results = self.search_with_exa(queries)

        # Step 5: Extract Jobs-to-be-Done
        jobs = self.extract_jobs_to_be_done(search_results, analysis_content)
        console.print(
            f"\n[green]✅ Extracted {len(jobs)} potential jobs-to-be-done[/green]"
        )

        # Step 6: Generate report
        report = self.generate_jtbd_report(jobs, search_results, elements)

        # Step 7: Save report
        with open(output_file, "w") as f:
            f.write(report)
        console.print(
            f"\n[green]✅ JTBD research report saved to {output_file}[/green]"
        )

        # Step 8: Extract and save pain points for clustering
        pain_points = self.extract_pain_points(jobs, search_results)
        pain_points_file = output_file.replace(".md", "_pain_points.txt")
        self.save_pain_points(pain_points, pain_points_file)

        # Display summary
        console.print(
            Panel(
                f"• Sources searched: {sum(len(v) for v in search_results.values())}\n"
                f"• Jobs identified: {len(jobs)}\n"
                f"• Categories covered: {len([k for k, v in search_results.items() if v])}\n"
                f"• Report size: {len(report.split())} words\n"
                f"• Pain points extracted: {len(pain_points)}",
                title="Research Summary",
                border_style="blue",
            )
        )

        console.print(f"\n[cyan]💡 Next step: Run clustering analysis[/cyan]")
        console.print(f"python cluster_jtbd.py {pain_points_file}")

        return report


def main():
    """
    Main entry point for the Jobs-to-be-Done researcher.

    Handles command-line argument parsing, initializes the JobsResearcher,
    and executes either test mode or the full JTBD research pipeline.

    Command-line Arguments:
        --input: Path to analysis results file from previous stage
        --output: Output filename for JTBD report
        --test: Test EXA API connection only

    Environment Requirements:
        - EXA_API_KEY: Required for search functionality
        - ANTHROPIC_API_KEY: Optional, enhances report synthesis

    Exit Codes:
        0: Success
        1: Configuration error or search failure
    """
    parser = argparse.ArgumentParser(
        description="Jobs-to-be-Done Research using EXA API",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Use default analysis file
  python jobs_researcher.py
  
  # Specify custom input and output
  python jobs_researcher.py --input my_analysis.md --output my_jtbd.md
  
  # Test EXA connection
  python jobs_researcher.py --test
        """,
    )

    parser.add_argument(
        "--input",
        type=str,
        default="analysis_results.md",
        help="Input analysis file (default: analysis_results.md)",
    )
    parser.add_argument(
        "--output",
        type=str,
        default="jtbd_research.md",
        help="Output JTBD report file (default: jtbd_research.md)",
    )
    parser.add_argument("--test", action="store_true", help="Test EXA connection")

    args = parser.parse_args()

    # Initialize researcher
    researcher = JobsResearcher()

    if args.test:
        # Test mode
        console.print("[cyan]Testing EXA connection...[/cyan]")
        try:
            result = researcher.exa.search("test query", num_results=1)
            console.print("[green]✅ EXA connection successful![/green]")
            if result.results:
                console.print(f"Sample result: {result.results[0].title}")
        except Exception as e:
            console.print(f"[red]❌ EXA test failed: {e}[/red]")
        return

    # Run JTBD research
    researcher.run(args.input, args.output)


if __name__ == "__main__":
    main()
