    def __init__(self):
        """
        Initialize EXA and Anthropic clients.

        Sets up the EXA search client (required) and optionally initializes
        the Anthropic client for AI-powered synthesis. Handles missing API
        keys gracefully, with EXA being mandatory and Anthropic optional.

        Raises:
            SystemExit: If EXA_API_KEY is not found in environment
        """
        # Load LLM configuration
        self.config_loader = ConfigLoader()
        
        # EXA setup
        self.exa_api_key = os.getenv("EXA_API_KEY")
        if not self.exa_api_key:
            console.print(
                "[red]Error: EXA_API_KEY not found in environment variables![/red]"
            )
            sys.exit(1)

        try:
            self.exa = Exa(self.exa_api_key)
        except Exception as e:
            console.print(f"[red]Error initializing EXA client: {e}[/red]")
            sys.exit(1)

        # Anthropic setup (for summarization)
        self.anthropic_api_key = os.getenv("ANTHROPIC_API_KEY")
        if self.anthropic_api_key:
            try:
                self.anthropic_client = anthropic.Anthropic(
                    api_key=self.anthropic_api_key
                )
                # Get model from config
                jtbd_settings = self.config_loader.get_model_settings('jtbd_synthesis')
                self.model = jtbd_settings.get('model', 'claude-3-5-sonnet-20241022')
            except Exception as e:
                console.print(
                    f"[yellow]Warning: Anthropic client initialization failed: {e}[/yellow]"
                )
                self.anthropic_client = None
        else:
            self.anthropic_client = None

