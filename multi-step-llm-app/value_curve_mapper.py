"""
Value Curve Mapper - Phase 2: Map Current Value Curves.

This module serves as the fourth stage in the 7-stage product innovation pipeline.
It takes opportunity zones from cluster_jtbd.py and performs deep competitive
analysis to identify industry norms, taboos, and disruption opportunities.

Key Features:
- EXA API integration for competitive intelligence gathering
- Claude Opus for deep industry analysis and pattern recognition
- Parallel processing of multiple opportunity zones
- Value curve mapping across competitive dimensions
- Disruption opportunity identification

Analysis Components:
1. Industry Norms - Common practices across competitors
2. Industry Taboos - What nobody does (and why)
3. Industry Dogma - Unquestioned assumptions
4. Value Dimensions - Key competitive factors
5. Disruption Opportunities - Where to break the rules

Usage:
    # Basic usage
    python value_curve_mapper.py opportunity_zones.json

    # Custom output
    python value_curve_mapper.py zones.json --output value_curves.json

    # Test mode
    python value_curve_mapper.py --test

Environment Variables Required:
    - EXA_API_KEY: EXA search API key
    - ANTHROPIC_API_KEY: Claude AI API key (Opus model)

Output:
    Creates 'value_curves.json' containing competitive analysis for each zone.
"""

