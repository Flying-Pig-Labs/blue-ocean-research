class ValueCurveMapper:
    """
    Map value curves for opportunity zones using EXA and Claude Opus.

    This class orchestrates competitive analysis by searching for industry
    intelligence, analyzing competitive patterns, and identifying opportunities
    for disruption through value curve innovation.

    Attributes:
        exa: EXA API client for competitive search
        anthropic_client: Claude API client (Opus model)
        model_opus: Claude Opus model identifier

    Example:
        mapper = ValueCurveMapper()
        curves = mapper.run("opportunity_zones.json")
    """

    def __init__(self):
        """
        Initialize API clients.

        Sets up EXA client for competitive intelligence search and
        Anthropic client with Claude Opus for deep analysis. Both
        APIs are required for the complete value curve mapping.

        Raises:
            SystemExit: If API keys are missing or initialization fails
        """
        # EXA setup
        self.exa_api_key = os.getenv("EXA_API_KEY")
        if not self.exa_api_key:
            console.print("[red]Error: EXA_API_KEY not found![/red]")
            sys.exit(1)

        try:
            self.exa = Exa(self.exa_api_key)
        except Exception as e:
            console.print(f"[red]Error initializing EXA client: {e}[/red]")
            sys.exit(1)

        # Anthropic setup for Opus
        self.anthropic_api_key = os.getenv("ANTHROPIC_API_KEY")
        if not self.anthropic_api_key:
            console.print("[red]Error: ANTHROPIC_API_KEY not found![/red]")
            sys.exit(1)

        try:
            self.anthropic_client = anthropic.Anthropic(api_key=self.anthropic_api_key)
            self.model_opus = "claude-3-opus-20240229"
        except Exception as e:
            console.print(f"[red]Error initializing Anthropic client: {e}[/red]")
            sys.exit(1)

    def load_opportunity_zones(self, filepath: str) -> Dict:
        """
        Load opportunity zones from clustering output.

        Reads the JSON file generated by cluster_jtbd.py containing
        opportunity zones, their descriptions, and cluster mappings.

        Args:
            filepath: Path to opportunity zones JSON file

        Returns:
            Dict: Complete opportunity zones data structure

        Raises:
            SystemExit: If file not found or JSON parsing error
        """
        try:
            with open(filepath, "r") as f:
                data = json.load(f)
            console.print(f"[green]✅ Loaded opportunity zones from {filepath}[/green]")
            return data
        except FileNotFoundError:
            console.print(f"[red]Error: File not found: {filepath}[/red]")
            sys.exit(1)
        except json.JSONDecodeError as e:
            console.print(f"[red]Error parsing JSON: {e}[/red]")
            sys.exit(1)

    def search_strategy_canvas(self, zone: Dict) -> Dict:
        """
        Search for competitive strategy canvas using EXA.

        Performs targeted searches to gather competitive intelligence
        about the opportunity zone, including market leaders, feature
        comparisons, pricing strategies, and value propositions.

        Search Strategy:
        - Combines zone description with competitive keywords
        - Includes cluster-specific terms for precision
        - Uses neural search for semantic understanding
        - Retrieves highlights and full text content

        Args:
            zone: Opportunity zone dictionary with name, description, clusters

        Returns:
            Dict: Competitive data with:
                - zone_name: Name of the opportunity zone
                - zone_description: Zone description
                - search_results: List of competitive insights
                - error: Error message if search failed (optional)
        """
        zone_name = zone.get("name", "Unknown Zone")
        zone_description = zone.get("description", "")
        clusters = zone.get("clusters_addressed", [])

        console.print(f"\n[cyan]🔍 Searching strategy canvas for: {zone_name}[/cyan]")

        # Construct search query for competitive analysis
        query = f"""
        {zone_description} competitive analysis strategy canvas value dimensions
        market leaders competitors features pricing comparison
        "{" OR ".join(clusters[:2]) if clusters else zone_name}"
        """

        try:
            # Search for competitive landscape
            results = self.exa.search_and_contents(
                query.strip(),
                num_results=10,
                text=True,
                highlights=True,
                use_autoprompt=True,
                type="neural",
            )

            # Extract competitive insights
            competitive_data = {
                "zone_name": zone_name,
                "zone_description": zone_description,
                "search_results": [],
            }

            for result in results.results:
                competitive_data["search_results"].append(
                    {
                        "url": result.url,
                        "title": result.title,
                        "text": result.text[:1500] if hasattr(result, "text") else "",
                        "highlights": result.highlights[:5]
                        if hasattr(result, "highlights")
                        else [],
                    }
                )

            console.print(
                f"[green]✅ Found {len(results.results)} competitive insights[/green]"
            )
            return competitive_data

        except Exception as e:
            console.print(f"[red]Error in EXA search: {e}[/red]")
            return {
                "zone_name": zone_name,
                "zone_description": zone_description,
                "search_results": [],
                "error": str(e),
            }

    def analyze_industry_norms(self, competitive_data: Dict) -> str:
        """
        Use Claude Opus to identify industry norms, taboos, and dogma.

        Performs deep analysis of competitive intelligence to extract:
        - Common practices all competitors follow
        - Industry taboos that nobody violates
        - Unquestioned assumptions (dogma)
        - Opportunities for differentiation

        Args:
            competitive_data: Search results from EXA containing
                competitive intelligence

        Returns:
            str: Comprehensive analysis of industry patterns
        """
        zone_name = competitive_data.get("zone_name", "Unknown")
        search_results = competitive_data.get("search_results", [])

        # Prepare context from search results
        context = f"Opportunity Zone: {zone_name}\n"
        context += f"Description: {competitive_data.get('zone_description', '')}\n\n"
        context += "Competitive Intelligence:\n"

        for i, result in enumerate(search_results[:5], 1):
            context += f"\n{i}. {result['title']}\n"
            context += f"   Key points: {', '.join(result.get('highlights', []))}\n"
            context += f"   Excerpt: {result['text'][:500]}...\n"

        prompt = """Based on this competitive intelligence, identify:

1. **Industry Norms**: What does everyone in this space do similarly?
2. **Sacred Cows**: What assumptions are never questioned?
3. **Taboos**: What do companies avoid doing or discussing?
4. **Dogma**: What beliefs guide decision-making across the industry?
5. **Blind Spots**: What are competitors collectively ignoring?

For each category, provide specific examples and explain why these exist.
Format your response with clear headers and bullet points."""

        try:
            message = self.anthropic_client.messages.create(
                model=self.model_opus,
                max_tokens=2500,
                temperature=0.7,
                system="You are a strategic analyst expert at identifying industry patterns and assumptions.",
                messages=[{"role": "user", "content": context + "\n\n" + prompt}],
            )

            return message.content[0].text

        except Exception as e:
            console.print(f"[red]Error in norms analysis: {e}[/red]")
            return f"Error analyzing industry norms: {str(e)}"

    def analyze_engineering_spectrum(self, competitive_data: Dict) -> str:
        """
        Use Claude Opus to identify over/under-engineered aspects.

        Analyzes the market to find:
        - Over-engineered features with limited appeal
        - Under-engineered aspects causing frustration
        - Complexity mismatches with user needs
        - Opportunities for simplification or sophistication

        This analysis helps identify ERRC opportunities:
        - Eliminate: Over-engineered features
        - Reduce: Unnecessary complexity
        - Raise: Under-served aspects
        - Create: Missing value dimensions

        Args:
            competitive_data: Search results containing market intelligence

        Returns:
            str: Detailed engineering spectrum analysis
        """
        zone_name = competitive_data.get("zone_name", "Unknown")
        search_results = competitive_data.get("search_results", [])

        # Prepare context
        context = f"Opportunity Zone: {zone_name}\n"
        context += f"Description: {competitive_data.get('zone_description', '')}\n\n"
        context += "Market Intelligence:\n"

        for i, result in enumerate(search_results[:5], 1):
            context += f"\n{i}. {result['title']}\n"
            context += f"   Insights: {result['text'][:600]}...\n"

        prompt = """Analyze the engineering and complexity spectrum in this market:

1. **OVER-ENGINEERED ASPECTS** (Few customers paying for high quality):
   - What features/services are too complex for most users?
   - What premium offerings have limited market appeal?
   - Where is perfectionism hurting accessibility?
   - What's unnecessarily sophisticated?

2. **UNDER-ENGINEERED ASPECTS** (Many customers accepting low quality):
   - What basic needs are poorly served?
   - Where are companies cutting too many corners?
   - What frustrations do users tolerate due to lack of alternatives?
   - What's overly simplified to the point of dysfunction?

3. **COMPLEXITY ANALYSIS**:
   - What's complex that should be simple?
   - What's simple that needs more sophistication?
   - Where is complexity adding value vs. creating friction?

Provide specific examples and explain the market dynamics behind each observation."""

        try:
            message = self.anthropic_client.messages.create(
                model=self.model_opus,
                max_tokens=2500,
                temperature=0.7,
                system="You are a product strategy expert analyzing market complexity and engineering decisions.",
                messages=[{"role": "user", "content": context + "\n\n" + prompt}],
            )

            return message.content[0].text

        except Exception as e:
            console.print(f"[red]Error in engineering analysis: {e}[/red]")
            return f"Error analyzing engineering spectrum: {str(e)}"

    def analyze_zone(self, zone: Dict, zone_index: int, total_zones: int) -> Dict:
        """
        Complete analysis for a single opportunity zone.

        Orchestrates the full analysis pipeline for one zone:
        1. EXA search for competitive landscape (sequential)
        2. Parallel Claude Opus analysis:
           - Industry norms and taboos
           - Engineering spectrum analysis

        The two-phase approach ensures search results inform
        the AI analysis for maximum insight quality.

        Args:
            zone: Opportunity zone dictionary
            zone_index: Current zone index (for progress display)
            total_zones: Total number of zones (for progress display)

        Returns:
            Dict: Complete analysis containing:
                - zone: Original zone data
                - competitive_data: EXA search results
                - industry_norms: Norms/taboos analysis
                - engineering_spectrum: Over/under-engineering analysis
        """
        console.print(
            f"\n[bold cyan]Analyzing Zone {zone_index + 1}/{total_zones}: {zone['name']}[/bold cyan]"
        )

        # Step 1: EXA search for competitive landscape (must complete first)
        competitive_data = self.search_strategy_canvas(zone)

        if not competitive_data.get("search_results"):
            console.print(
                f"[yellow]Warning: No competitive data found for {zone['name']}[/yellow]"
            )
            return {
                "zone": zone,
                "competitive_data": competitive_data,
                "industry_norms": "No data available",
                "engineering_spectrum": "No data available",
            }

        # Step 2: Parallel Opus analysis (only after EXA completes)
        console.print(f"[cyan]🧠 Running parallel Opus analysis...[/cyan]")

        with ThreadPoolExecutor(max_workers=2) as executor:
            # Submit both Opus tasks
            norms_future = executor.submit(
                self.analyze_industry_norms, competitive_data
            )
            engineering_future = executor.submit(
                self.analyze_engineering_spectrum, competitive_data
            )

            # Wait for both to complete
            futures = {
                norms_future: "industry_norms",
                engineering_future: "engineering_spectrum",
            }

            results = {}
            for future in as_completed(futures):
                task_name = futures[future]
                try:
                    results[task_name] = future.result()
                    console.print(f"[green]✅ Completed: {task_name}[/green]")
                except Exception as e:
                    console.print(f"[red]Error in {task_name}: {e}[/red]")
                    results[task_name] = f"Error: {str(e)}"

        return {
            "zone": zone,
            "competitive_data": competitive_data,
            "industry_norms": results.get("industry_norms", "Error"),
            "engineering_spectrum": results.get("engineering_spectrum", "Error"),
        }

    def generate_value_curve_report(self, analyses: List[Dict]) -> str:
        """
        Generate comprehensive value curve mapping report.

        Creates a structured markdown report containing:
        - Executive summary with opportunity overview
        - Detailed analysis for each zone
        - Competitive landscape insights
        - Industry norms and sacred cows
        - Engineering spectrum findings
        - Value curve synthesis
        - Strategic recommendations

        Args:
            analyses: List of completed zone analyses

        Returns:
            str: Complete markdown-formatted report
        """
        report = "# Value Curve Mapping Report\n\n"
        report += f"Generated on: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n"
        report += "## Executive Summary\n\n"
        report += (
            f"Analyzed {len(analyses)} opportunity zones to map current value curves "
        )
        report += "and identify disruption opportunities.\n\n"

        # Summary table
        report += "### Opportunity Zones Overview\n\n"
        report += "| Zone | Importance | Key Disruption Opportunity |\n"
        report += "|------|------------|---------------------------|\n"

        for analysis in analyses:
            zone = analysis["zone"]
            importance = zone.get("importance_percentage", 0)

            # Extract key opportunity from norms analysis
            norms_text = analysis.get("industry_norms", "")
            key_opportunity = "See detailed analysis"
            if "Sacred Cows:" in norms_text:
                # Try to extract first sacred cow as key opportunity
                try:
                    sacred_start = norms_text.find("Sacred Cows:")
                    sacred_section = norms_text[sacred_start : sacred_start + 200]
                    if "•" in sacred_section:
                        key_opportunity = (
                            sacred_section.split("•")[1].split("\n")[0].strip()[:50]
                            + "..."
                        )
                except Exception:
                    pass

            report += f"| {zone['name']} | {importance}% | {key_opportunity} |\n"

        report += "\n---\n\n"

        # Detailed analysis for each zone
        for i, analysis in enumerate(analyses):
            zone = analysis["zone"]
            report += f"## {i + 1}. {zone['name']} (Priority: {zone.get('importance_percentage', 0)}%)\n\n"
            report += f"**Description**: {zone.get('description', 'N/A')}\n\n"
            report += f"**Clusters Addressed**: {', '.join(zone.get('clusters_addressed', []))}\n\n"

            # Competitive landscape summary
            comp_data = analysis.get("competitive_data", {})
            search_results = comp_data.get("search_results", [])
            if search_results:
                report += "### Competitive Landscape\n\n"
                report += f"*{len(search_results)} sources analyzed*\n\n"
                for j, result in enumerate(search_results[:3]):
                    report += f"{j + 1}. [{result['title']}]({result['url']})\n"
                report += "\n"

            # Industry norms and taboos
            report += "### Industry Norms & Sacred Cows\n\n"
            report += analysis.get("industry_norms", "Analysis not available") + "\n\n"

            # Engineering spectrum
            report += "### Engineering Spectrum Analysis\n\n"
            report += (
                analysis.get("engineering_spectrum", "Analysis not available") + "\n\n"
            )

            # Value curve insights
            report += "### Value Curve Insights\n\n"
            report += self._synthesize_value_curve(analysis) + "\n\n"

            report += "---\n\n"

        # Strategic recommendations
        report += "## Strategic Recommendations\n\n"
        report += self._generate_recommendations(analyses)

        return report

    def _synthesize_value_curve(self, analysis: Dict) -> str:
        """
        Synthesize value curve insights from the analysis.

        Extracts key patterns from industry norms and engineering
        analysis to identify:
        - Convergent value dimensions (sameness)
        - Elimination opportunities (over-engineering)
        - Creation opportunities (under-served needs)
        - Differentiation potential

        Args:
            analysis: Complete zone analysis results

        Returns:
            str: Synthesized value curve insights
        """
        insights = []

        # Extract key patterns
        norms = analysis.get("industry_norms", "")
        engineering = analysis.get("engineering_spectrum", "")

        # Look for value dimensions
        if "everyone" in norms.lower() or "all companies" in norms.lower():
            insights.append(
                "**Convergent Value Dimensions**: Industry shows high similarity in core offerings"
            )

        if "over-engineered" in engineering.lower():
            insights.append(
                "**Elimination Opportunities**: Features that could be removed to reduce cost/complexity"
            )

        if "under-engineered" in engineering.lower():
            insights.append(
                "**Creation Opportunities**: New value dimensions that could differentiate"
            )

        if not insights:
            insights.append(
                "**Further Analysis Needed**: Consider deeper competitive research"
            )

        return "\n".join(insights)

    def _generate_recommendations(self, analyses: List[Dict]) -> str:
        """
        Generate strategic recommendations based on all analyses.

        Synthesizes insights across all zones to provide:
        - High-priority disruption opportunities
        - Cross-zone synergies
        - Implementation priorities
        - Risk considerations

        Args:
            analyses: All completed zone analyses

        Returns:
            str: Strategic recommendations section
        """
        recommendations = []

        # Analyze patterns across all zones
        all_norms = []
        all_engineering = []

        for analysis in analyses:
            all_norms.append(analysis.get("industry_norms", ""))
            all_engineering.append(analysis.get("engineering_spectrum", ""))

        # Common patterns
        if any("premium" in eng.lower() for eng in all_engineering):
            recommendations.append(
                "1. **Blue Ocean Strategy**: Consider eliminating premium features that few value while creating new accessibility features"
            )

        if any("complex" in eng.lower() for eng in all_engineering):
            recommendations.append(
                "2. **Simplification Play**: Radical simplification could unlock underserved segments"
            )

        if any("taboo" in norm.lower() for norm in all_norms):
            recommendations.append(
                "3. **Taboo Breaking**: Challenge industry taboos as potential differentiation points"
            )

        if not recommendations:
            recommendations.append(
                "1. **Deep Dive Required**: Conduct primary research to validate findings"
            )

        recommendations.append("\n### Next Steps\n")
        recommendations.append("- Validate findings with customer interviews")
        recommendations.append("- Prototype value curve alternatives")
        recommendations.append("- Test willingness to pay for new value propositions")

        return "\n".join(recommendations)

    def save_results(
        self,
        analyses: List[Dict],
        report: str,
        json_output: str = "value_curves.json",
        report_output: str = "value_curves_report.md",
    ):
        """
        Save analysis results.

        Persists both structured JSON data and human-readable markdown
        report for downstream processing and review.

        Args:
            analyses: List of completed zone analyses
            report: Generated markdown report
            json_output: Path for JSON output file
            report_output: Path for markdown report file
        """
        # Save JSON data
        output_data = {
            "metadata": {
                "timestamp": datetime.now().isoformat(),
                "n_zones_analyzed": len(analyses),
            },
            "analyses": analyses,
        }

        with open(json_output, "w") as f:
            json.dump(output_data, f, indent=2)
        console.print(f"[green]✅ Analysis data saved to {json_output}[/green]")

        # Save markdown report
        with open(report_output, "w") as f:
            f.write(report)
        console.print(f"[green]✅ Report saved to {report_output}[/green]")

    def run(
        self,
        zones_file: str,
        json_output: str = "value_curves.json",
        report_output: str = "value_curves_report.md",
    ):
        """
        Main execution flow for value curve mapping.

        Orchestrates the complete analysis pipeline:
        1. Load opportunity zones from previous stage
        2. Display zones to be analyzed
        3. Analyze each zone (EXA search + Opus analysis)
        4. Generate comprehensive report
        5. Save results and display summary

        Args:
            zones_file: Path to opportunity zones JSON from clustering
            json_output: Path for structured output data
            report_output: Path for markdown report
        """
        console.print(
            Panel.fit(
                "[bold green]Value Curve Mapping Analysis[/bold green]\n"
                "Phase 2: Map Current Value Curves",
                border_style="green",
            )
        )

        # Load opportunity zones
        zones_data = self.load_opportunity_zones(zones_file)
        opportunity_zones = zones_data.get("opportunity_zones", {}).get(
            "opportunity_zones", []
        )

        if not opportunity_zones:
            console.print("[red]Error: No opportunity zones found in input file[/red]")
            sys.exit(1)

        console.print(
            f"\n[cyan]Found {len(opportunity_zones)} opportunity zones to analyze[/cyan]"
        )

        # Display zones to be analyzed
        table = Table(title="Opportunity Zones")
        table.add_column("Zone", style="cyan")
        table.add_column("Importance", style="magenta")
        table.add_column("Impact", style="green")

        for zone in opportunity_zones:
            table.add_row(
                zone["name"],
                f"{zone.get('importance_percentage', 0)}%",
                zone.get("potential_impact", "Unknown"),
            )

        console.print(table)

        # Analyze each zone
        analyses = []
        for i, zone in enumerate(opportunity_zones):
            analysis = self.analyze_zone(zone, i, len(opportunity_zones))
            analyses.append(analysis)

        # Generate report
        console.print("\n[cyan]📊 Generating value curve report...[/cyan]")
        report = self.generate_value_curve_report(analyses)

        # Save results
        self.save_results(analyses, report, json_output, report_output)

        # Display summary
        console.print(
            Panel(
                f"✅ Analysis complete!\n\n"
                f"• Zones analyzed: {len(analyses)}\n"
                f"• Competitive sources: {sum(len(a['competitive_data'].get('search_results', [])) for a in analyses)}\n"
                f"• Industry norms identified: Yes\n"
                f"• Engineering gaps mapped: Yes\n\n"
                f"Next: Review {report_output} for strategic insights",
                title="Value Curve Mapping Complete",
                border_style="green",
            )
        )


