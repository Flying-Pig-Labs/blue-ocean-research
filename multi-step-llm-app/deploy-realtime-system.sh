#!/bin/bash
set -e

# Multi-Step LLM Pipeline - Real-time System Deployment Script
# This script deploys the complete GraphQL/AppSync infrastructure with React Flow frontend

echo "🚀 Deploying Multi-Step LLM Pipeline with Real-time Updates"
echo "=========================================================="

# Configuration
STACK_NAME="multi-step-pipeline"
ENVIRONMENT="${ENVIRONMENT:-production}"
AWS_REGION="${AWS_REGION:-us-east-1}"
AWS_PROFILE="${AWS_PROFILE:-default}"

echo "Environment: $ENVIRONMENT"
echo "Region: $AWS_REGION"
echo "Profile: $AWS_PROFILE"
echo ""

# Check prerequisites
echo "🔍 Checking prerequisites..."

# Check if AWS CLI is installed
if ! command -v aws &> /dev/null; then
    echo "❌ AWS CLI is not installed. Please install it first."
    exit 1
fi

# Check if SAM CLI is installed
if ! command -v sam &> /dev/null; then
    echo "❌ SAM CLI is not installed. Please install it first."
    exit 1
fi

# Check if Node.js is installed
if ! command -v node &> /dev/null; then
    echo "❌ Node.js is not installed. Please install it first."
    exit 1
fi

# Verify AWS credentials
if ! aws sts get-caller-identity --profile "$AWS_PROFILE" &> /dev/null; then
    echo "❌ AWS credentials not configured for profile: $AWS_PROFILE"
    exit 1
fi

echo "✅ Prerequisites check passed"
echo ""

# Step 1: Install Lambda dependencies
echo "📦 Installing Lambda dependencies..."

# GraphQL resolver dependencies
if [ -d "graphql/resolvers" ]; then
    cd graphql/resolvers
    echo "Installing resolver dependencies..."
    npm install
    cd ../..
else
    echo "⚠️  GraphQL resolver directory not found"
fi

# Stream processor dependencies
if [ -d "graphql/stream-processor" ]; then
    cd graphql/stream-processor
    echo "Installing stream processor dependencies..."
    npm install
    cd ../..
else
    echo "⚠️  Stream processor directory not found"
fi

# Python dependencies for enhanced Lambda handler
echo "Installing Python dependencies..."
pip install -r requirements.txt --target ./
echo ""

# Step 2: Build SAM application
echo "🔨 Building SAM application..."
sam build --use-container

if [ $? -ne 0 ]; then
    echo "❌ SAM build failed"
    exit 1
fi

echo "✅ SAM build completed"
echo ""

# Step 3: Deploy infrastructure
echo "🚀 Deploying infrastructure..."

sam deploy \
    --stack-name "$STACK_NAME" \
    --capabilities CAPABILITY_IAM \
    --parameter-overrides \
        EnvironmentName="$ENVIRONMENT" \
    --resolve-s3 \
    --region "$AWS_REGION" \
    --profile "$AWS_PROFILE" \
    --no-confirm-changeset

if [ $? -ne 0 ]; then
    echo "❌ SAM deployment failed"
    exit 1
fi

echo "✅ Infrastructure deployed successfully"
echo ""

# Step 4: Get stack outputs
echo "📊 Retrieving stack outputs..."

STACK_OUTPUTS=$(aws cloudformation describe-stacks \
    --stack-name "$STACK_NAME" \
    --region "$AWS_REGION" \
    --profile "$AWS_PROFILE" \
    --query 'Stacks[0].Outputs' \
    --output json)

if [ $? -ne 0 ]; then
    echo "❌ Failed to retrieve stack outputs"
    exit 1
fi

# Extract key outputs
GRAPHQL_URL=$(echo "$STACK_OUTPUTS" | jq -r '.[] | select(.OutputKey=="GraphQLApiUrl") | .OutputValue')
GRAPHQL_API_KEY=$(echo "$STACK_OUTPUTS" | jq -r '.[] | select(.OutputKey=="GraphQLApiKey") | .OutputValue')
REST_API_URL=$(echo "$STACK_OUTPUTS" | jq -r '.[] | select(.OutputKey=="ApiEndpoint") | .OutputValue')

echo "GraphQL API URL: $GRAPHQL_URL"
echo "REST API URL: $REST_API_URL"
echo ""

# Step 5: Create frontend environment file
echo "🌐 Configuring frontend environment..."

mkdir -p frontend
cat > frontend/.env << EOF
# Multi-Step Pipeline Frontend Configuration
# Generated by deploy-realtime-system.sh on $(date)

# GraphQL Configuration
REACT_APP_GRAPHQL_URL=$GRAPHQL_URL
REACT_APP_GRAPHQL_API_KEY=$GRAPHQL_API_KEY

# REST API Configuration  
REACT_APP_REST_API_URL=$REST_API_URL

# AWS Configuration
REACT_APP_AWS_REGION=$AWS_REGION
REACT_APP_ENVIRONMENT=$ENVIRONMENT

# Application Configuration
REACT_APP_APP_NAME=Multi-Step LLM Pipeline
REACT_APP_VERSION=1.0.0
EOF

echo "✅ Frontend environment configured"
echo ""

# Step 6: Build and install frontend (optional)
if [ -f "frontend/package.json" ]; then
    echo "🎨 Building frontend..."
    cd frontend
    
    # Install dependencies
    if [ ! -d "node_modules" ]; then
        echo "Installing frontend dependencies..."
        npm install
    fi
    
    # Build for production
    echo "Building frontend for production..."
    npm run build
    
    if [ $? -eq 0 ]; then
        echo "✅ Frontend built successfully"
        echo "📁 Build files available in: frontend/build/"
    else
        echo "⚠️  Frontend build failed (non-critical)"
    fi
    
    cd ..
fi

# Step 7: Test the deployment
echo "🧪 Testing deployment..."

# Test REST API
echo "Testing REST API..."
REST_TEST_RESPONSE=$(curl -s -o /dev/null -w "%{http_code}" "$REST_API_URL/status/test-job")
if [ "$REST_TEST_RESPONSE" = "404" ]; then
    echo "✅ REST API is responding (expected 404 for test job)"
else
    echo "⚠️  REST API test returned: $REST_TEST_RESPONSE"
fi

# Test GraphQL API (simple introspection query)
echo "Testing GraphQL API..."
GRAPHQL_TEST_RESPONSE=$(curl -s -X POST \
    -H "Content-Type: application/json" \
    -H "x-api-key: $GRAPHQL_API_KEY" \
    -d '{"query":"query { __schema { types { name } } }"}' \
    "$GRAPHQL_URL")

if echo "$GRAPHQL_TEST_RESPONSE" | jq -e '.data' > /dev/null 2>&1; then
    echo "✅ GraphQL API is responding"
else
    echo "⚠️  GraphQL API test failed"
    echo "Response: $GRAPHQL_TEST_RESPONSE"
fi

echo ""

# Step 8: Display deployment summary
echo "🎉 Deployment completed successfully!"
echo "======================================"
echo ""
echo "📋 Deployment Summary:"
echo "  Stack Name: $STACK_NAME"
echo "  Environment: $ENVIRONMENT"
echo "  Region: $AWS_REGION"
echo ""
echo "🔗 API Endpoints:"
echo "  GraphQL API: $GRAPHQL_URL"
echo "  REST API: $REST_API_URL"
echo ""
echo "🔑 API Key: $GRAPHQL_API_KEY"
echo ""
echo "🎨 Frontend:"
echo "  Environment file: frontend/.env"
if [ -d "frontend/build" ]; then
    echo "  Build files: frontend/build/"
    echo "  To serve locally: cd frontend && npm start"
fi
echo ""
echo "📖 Next Steps:"
echo "  1. Start the frontend: cd frontend && npm start"
echo "  2. Open http://localhost:3000 in your browser"
echo "  3. Create a new execution to test real-time updates"
echo "  4. Monitor CloudWatch logs for debugging"
echo ""
echo "🔧 Useful Commands:"
echo "  View logs: aws logs tail /aws/lambda/${STACK_NAME}-GraphQLResolverFunction --follow --profile $AWS_PROFILE"
echo "  Update stack: sam deploy --no-confirm-changeset --profile $AWS_PROFILE"
echo "  Delete stack: aws cloudformation delete-stack --stack-name $STACK_NAME --profile $AWS_PROFILE"
echo ""
echo "✨ Real-time pipeline visualization is now ready!"